export function assertCurriculumPracticeLibraryProvenance() {
  if (CURRICULUM_PRACTICE_REVIEW_MANIFEST.length !== CURRICULUM_PRACTICE_LIBRARY.length) {
    throw new Error("Every curriculum practice item requires a provenance review record.");
  }
  const reviewedIds = new Set(CURRICULUM_PRACTICE_REVIEW_MANIFEST.map((record) => record.questionId));
  for (const question of CURRICULUM_PRACTICE_LIBRARY) {
    const review = CURRICULUM_PRACTICE_REVIEW_MANIFEST.find((record) => record.questionId === question.questionId);
    if (!reviewedIds.has(question.questionId) || !review || !review.originalContentAttested || review.proprietaryContentReview !== "cleared" || review.logicGamesReview !== "cleared") {
      throw new Error(`${question.questionId} is missing required original-content provenance review.`);
    }
    const searchableText = [question.questionText, question.optionA, question.optionB, question.optionC, question.optionD, question.optionE, question.explanation].join(" ");
    if (/\b(?:lsac|preptest|logic games?)\b/i.test(searchableText)) {
      throw new Error(`${question.questionId} contains prohibited source or excluded-content references.`);
    }
  }
}
